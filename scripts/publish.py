#!/usr/bin/env python3
"""Publish ui-elements to Cloudflare Pages (replaces the GitHub mirror + jsDelivr as the publish step).

    python3 scripts/publish.py                 # build the site into dist/ only (no network)
    python3 scripts/publish.py --deploy        # build, then upload dist/ with wrangler (direct upload)

Site layout (one Pages project, default name "ui-elements", so https://<project>.pages.dev):

    /components/<file>.js, /tokens.css, /components.json, /demo/, /docs/   the current checkout (main)
    /v0.1.0/components/<file>.js, ...                                      every v* git tag, from `git archive`

Pin a tag in consumer URLs: /v<x.y.z>/ paths never change once published (served `immutable`); the root
follows main and is cached for 5 minutes. Every path sends `Access-Control-Allow-Origin: *`, so pages on
other origins can import the modules, as they do from jsDelivr. Relative `./_shared/*.js` imports resolve
under both roots, and swapOutlet finds `components.json` next to `components/`.

--deploy runs `npx wrangler@WRANGLER pages deploy` and needs CLOUDFLARE_API_TOKEN (Pages: Edit) and
CLOUDFLARE_ACCOUNT_ID in the environment; nothing here reads or prints them. The Pages project must exist
(`npx wrangler pages project create ui-elements --production-branch main`, once).

Stdlib only; nothing a consumer loads is built or changed.
"""
import argparse, io, os, re, shutil, subprocess, sys, tarfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WRANGLER = "4.169.0"
PROJECT = "ui-elements"
# What a consumer can load (and the live demo needs). Tests, scripts and media for the README stay out.
PUBLISH = ["components", "demo", "docs", "tokens.css", "components.json", "README.md", "AGENTS.md"]
SKIP_DIRS = {os.path.join("docs", "media")}
TAG = re.compile(r"^v\d+\.\d+\.\d+$")


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout


def tags():
    return sorted((t for t in git("tag", "-l", "v*").split() if TAG.match(t)),
                  key=lambda t: tuple(int(x) for x in t[1:].split(".")))


def copy_worktree(dst):
    for name in PUBLISH:
        src = os.path.join(ROOT, name)
        if os.path.isdir(src):
            shutil.copytree(src, os.path.join(dst, name),
                            ignore=lambda d, names: [n for n in names if os.path.relpath(os.path.join(d, n), ROOT) in SKIP_DIRS])
        elif os.path.exists(src):
            shutil.copy2(src, os.path.join(dst, name))


def extract_ref(ref, dst):
    """The published paths of git ref `ref`, written under dst (paths missing at that ref are skipped)."""
    present = [p for p in PUBLISH if p in set(git("ls-tree", "--name-only", ref).split())]
    data = subprocess.run(["git", "archive", "--format=tar", ref, *present], cwd=ROOT, check=True, capture_output=True).stdout
    with tarfile.open(fileobj=io.BytesIO(data)) as tar:
        members = [m for m in tar.getmembers()
                   if not any(m.name == s or m.name.startswith(s + "/") for s in SKIP_DIRS)]
        tar.extractall(dst, members=members, filter="data")


def headers(versions):
    out = ["# Generated by scripts/publish.py (Cloudflare Pages _headers).",
           "/*", "  Access-Control-Allow-Origin: *", "  X-Content-Type-Options: nosniff",
           "  Cache-Control: public, max-age=300", ""]
    for v in versions:
        out += [f"/{v}/*", "  ! Cache-Control", "  Cache-Control: public, max-age=31536000, immutable", ""]
    return "\n".join(out)


def build(out, versions=None):
    """Write the site into `out`. versions: {path name: git ref}; default every v* tag."""
    versions = {t: t for t in tags()} if versions is None else versions
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)
    copy_worktree(out)
    for name, ref in versions.items():
        extract_ref(ref, os.path.join(out, name))
    with open(os.path.join(out, "_headers"), "w") as f:
        f.write(headers(list(versions)))
    head = git("rev-parse", "HEAD").strip()
    with open(os.path.join(out, "version.txt"), "w") as f:
        f.write(f"main {head}\n" + "".join(f"{n} {ref}\n" for n, ref in versions.items()))
    return list(versions)


def deploy(out, project):
    missing = [k for k in ("CLOUDFLARE_API_TOKEN", "CLOUDFLARE_ACCOUNT_ID") if not os.environ.get(k)]
    if missing:
        sys.exit(f"publish: {', '.join(missing)} not set; built {out} but did not deploy")
    head = git("rev-parse", "HEAD").strip()
    cmd = ["npx", "--yes", f"wrangler@{WRANGLER}", "pages", "deploy", out, "--project-name", project,
           "--branch", "main", "--commit-hash", head, "--commit-dirty=true"]
    print("+", " ".join(cmd), flush=True)
    sys.exit(subprocess.run(cmd, cwd=ROOT).returncode)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", default=os.path.join(ROOT, "dist"), help="output directory (default dist/, gitignored)")
    ap.add_argument("--deploy", action="store_true", help="upload the built site to Cloudflare Pages")
    ap.add_argument("--project", default=PROJECT, help=f"Pages project name (default {PROJECT})")
    a = ap.parse_args()
    versions = build(a.out)
    files = sum(len(f) for _, _, f in os.walk(a.out))
    print(f"built {a.out}: main + {len(versions)} tag(s) {' '.join(versions) or '(none)'}, {files} files")
    if a.deploy:
        deploy(a.out, a.project)


if __name__ == "__main__":
    main()
