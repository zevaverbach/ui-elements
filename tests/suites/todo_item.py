@test("todo-item", "accessibility", desc='Every control has an accessible name, and the Tab order is grip, checkbox, steps, mic, edit, delete.', component=C, init_scripts=[SPEECH_MOCK])
def _(t):
    open_fixture(t, '<button id="before">before</button><ui-todo-item id="a" text="Buy milk" progress="25"></ui-todo-item>')
    p = t.page
    t.step("Every control has an accessible name", "#a")
    names = p.evaluate("""() => { const r = document.getElementById('a').shadowRoot;
      return [...r.querySelectorAll('button, input')].filter(e => !e.hidden && e.offsetParent !== null).map(e => ({cls: e.className, name: e.getAttribute('aria-label') || e.title || ''})); }""")
    for n in names:
        check(n["name"], f"control .{n['cls']} has no accessible name")
    eq(p.get_attribute("#a .check", "aria-label"), "Buy milk")
    check("Reorder Buy milk" in p.get_attribute("#a .handle", "aria-label"), "handle label names the item")
    eq([p.get_attribute(f"#a .step[data-v='{v}']", "aria-label") for v in (25, 50, 75, 100)], [f"Set {v} percent" for v in (25, 50, 75, 100)])
    eq(p.get_attribute("#a .steps", "role"), "group")
    eq(p.get_attribute("#a [role=status]", "aria-live"), "assertive")
    t.step("Tab order: grip, checkbox, steps, mic, edit, delete", "#a")
    p.focus("#before")
    seen = []
    for _ in range(9):
        p.keyboard.press("Tab")
        f = focused(p)
        if f[0] != "ui-todo-item":
            break
        seen.append(f[-1].replace("button.icon-btn", "button").split(".")[0] + ":" + (p.evaluate("document.getElementById('a').shadowRoot.activeElement.className")))
    classes = [s.split(":")[1].split(" ")[-1] if s.split(":")[1] else "" for s in seen]
    order = [c for c in classes]
    check(order[0].endswith("handle"), f"first stop should be the grip, got {order}")
    check("check" in order[1], f"second stop should be the checkbox, got {order}")
    check(order[-1].endswith("del") or "del" in order[-1], f"last stop should be delete, got {order}")
    check(order.index(next(c for c in order if "mic" in c)) > order.index(next(c for c in order if "step" in c)), "steps come before the mic")
