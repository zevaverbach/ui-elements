@test("todo-item", "inline-edit", desc='Double-clicking the text edits it: Enter saves, Escape cancels, and an empty value is not saved.', component=C)
def _(t):
    open_fixture(t, '<ui-todo-item id="a" text="Buy milk"></ui-todo-item>')
    t.capture_events(*EVENTS)
    p = t.page
    t.step("Double-click the text to edit", "#a")
    p.dblclick("#a .text")
    check(p.locator("#a .edit").is_visible(), "edit field visible")
    p.wait_for_function("document.getElementById('a').shadowRoot.activeElement?.classList.contains('edit')")
    t.step("Type a new value and press Enter", "#a")
    p.keyboard.press("Control+A"); p.keyboard.type("Buy oat milk"); p.keyboard.press("Enter")
    eq(p.inner_text("#a .text"), "Buy oat milk")
    eq(t.events("ui-edit")[-1]["detail"], {"text": "Buy oat milk", "previousText": "Buy milk"})
    t.step("Escape cancels an edit", "#a")
    p.click("#a .editbtn"); p.wait_for_timeout(100)
    p.keyboard.press("Control+A"); p.keyboard.type("nope"); p.keyboard.press("Escape")
    eq(p.inner_text("#a .text"), "Buy oat milk")
    eq(len(t.events("ui-edit")), 1, "cancel emits no ui-edit")
    t.step("An empty value is not saved", "#a")
    p.click("#a .editbtn"); p.wait_for_timeout(100)
    p.keyboard.press("Control+A"); p.keyboard.press("Backspace"); p.keyboard.press("Enter")
    eq(p.inner_text("#a .text"), "Buy oat milk")
    t.step("Leaving the field (blur) saves", "#a")
    p.click("#a .editbtn"); p.wait_for_timeout(100)
    p.keyboard.press("Control+A"); p.keyboard.type("Buy bread")
    p.evaluate("document.activeElement.blur?.(); document.getElementById('a').shadowRoot.activeElement?.blur()")
    p.wait_for_timeout(100)
    eq(p.inner_text("#a .text"), "Buy bread")

