    open_fixture(t, LIST)
    t.capture_events(*EVENTS)
    p = t.page
    t.step("Focus Alpha's grip and press Space to grab", "#a")
    p.focus("#a .handle"); p.keyboard.press("Space")
    eq(p.get_attribute("#a .handle", "aria-pressed"), "true")
    check("Grabbed" in p.inner_text("#a [role=status]") or p.wait_for_function("document.getElementById('a').shadowRoot.querySelector('[role=status]').textContent.includes('Grabbed')"), "announced")
