@test("todo-item", "attributes-and-properties", desc='Attributes and properties stay in sync: `text`, `checked`, `label` (eyebrow), `progress` (steps) and the `editing` attribute.', component=C)
def _(t):
    open_fixture(t, '<ui-todo-item id="a" text="Buy milk"></ui-todo-item>')
    t.step("Attribute `text` renders, property `text` reflects", "#a")
    p = t.page
    eq(p.inner_text("#a .text"), "Buy milk")
    p.evaluate("document.getElementById('a').text = 'Buy oat milk'")
    eq(p.get_attribute("#a", "text"), "Buy oat milk", "text property reflects to attribute")
    t.step("`checked` attribute and property", "#a")
    p.evaluate("document.getElementById('a').checked = true")
    check(p.get_attribute("#a", "checked") is not None, "checked property reflects")
    check(p.is_checked("#a .check"), "checkbox shows checked")
    p.evaluate("document.getElementById('a').removeAttribute('checked')")
    check(not p.is_checked("#a .check"), "removing the attribute unchecks")
    t.step("`label` shows an eyebrow, `progress` shows steps", "#a")
    p.evaluate("const a = document.getElementById('a'); a.setAttribute('label', 'Medium'); a.progress = 50")
    eq(p.text_content("#a .eyebrow"), "Medium")
    eq(p.locator("#a .step.on").count(), 2, "50% lights two of four steps")
    eq(p.evaluate("document.getElementById('a').progress"), 50)
    p.evaluate("document.getElementById('a').progress = null")
    check(p.locator("#a .steps").is_hidden(), "no progress attribute hides the steps")
    t.step("`editing` attribute opens the edit field", "#a")
    p.evaluate("document.getElementById('a').editing = true")
    check(p.locator("#a .edit").is_visible() and p.locator("#a .text").is_hidden(), "edit field replaces the text")
    t.step("`no-reorder` hides the handle", "#a")
    p.evaluate("document.getElementById('a').setAttribute('no-reorder', '')")
    check(p.locator("#a .handle").is_hidden(), "handle hidden")
    t.step("`meta` slot renders slotted content", "#a")
    mount(t, '<ui-todo-item id="m" text="x"><small slot="meta">Due soon</small></ui-todo-item>')
    check(p.evaluate("document.getElementById('m').shadowRoot.querySelector('slot[name=meta]').assignedNodes().length") == 1, "slotted node assigned")

@test("todo-item", "toggle", desc='Ticking the checkbox strikes the text through and emits ui-toggle; unticking reverses it.', component=C)
def _(t):
    open_fixture(t, '<ui-todo-item id="a" text="Buy milk"></ui-todo-item>')
    t.capture_events(*EVENTS)
    t.step("Tick the checkbox", "#a")
    t.page.click("#a .check")
    ev = t.events("ui-toggle")
    eq(len(ev), 1, "one ui-toggle")
    eq(ev[0]["detail"], {"checked": True, "progress": None})
    check(ev[0]["bubbles"] and ev[0]["composed"], "event bubbles and is composed")
    eq(ev[0]["target"], "ui-todo-item#a")
    t.step("The text is struck through", "#a")
    check("line-through" in t.page.evaluate("getComputedStyle(document.getElementById('a').shadowRoot.querySelector('.text')).textDecorationLine"), "struck through")
    t.step("Untick it", "#a")
    t.page.click("#a .check")
    eq(t.events("ui-toggle")[1]["detail"]["checked"], False)
    check(not t.page.evaluate("document.getElementById('a').checked"), "checked property is false")

